// Bind unambiguous static paint layers to PNGs. Layout, text, borders, focus,
// animation, progress and canvas rendering remain owned by their feature CSS/JS.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../bar-playtest');
const manifest=require('../bar-playtest/data/presentation/generated-art/manifest.json');
const candidates=new Map(),used=[];
const supported=/^(?:#(?:service-panel|prep-recipe-detail)|(?:div|section|aside|article|figure|span|button|i|kbd)\.(?:inventory-slot|prep-|recipe-|shelf-arrow|service-|upkeep-ledger|sales-balance|johnny-unlock|unlock-art|modal-backdrop|day0-seat-legend|controls-motion-card|mix-detail|mix-tutorial|mix-lesson|mix-guide|mix-direction|mix-cinematic|mix-motion|pour-tilt-track|pour-tilt-warning|pour-top-readout|campaign-skip|campaign-modal-shade|outside-controls-shade|outside-overlay|guest-card|world-choice-confirm))/;
for(const r of manifest.records){
 if(r.kind!=='background')continue;
 for(const s of r.sources){
  const selector=s.selector;if(!selector||!supported.test(selector)||/[ /]|::/.test(selector))continue;
  const state=/호버/.test(s.title)?'hover':/누름/.test(s.title)?'active':/포커스/.test(s.title)?'focus-visible':'normal';
  const key=selector+'|'+state;
  if(!candidates.has(key))candidates.set(key,new Map());candidates.get(key).set(r.path,r);
 }
}
const lines=['/* Generated by tools/build-generated-ui-css.cjs. PNG paint only; no layout/input rules. */'];
function rule(selector,r){
 used.push('assets/01.ArtResources/'+r.path);
 lines.push(selector+'{background-color:transparent;background-image:url("../../../assets/01.ArtResources/'+r.path+'");background-size:100% 100%;background-position:center;background-repeat:no-repeat;background-origin:border-box;background-clip:border-box}');
}
for(const [key,values]of candidates){
 if(values.size!==1)continue;const [selector,state]=key.split('|');
 const button=selector.startsWith('button');
 const suffix=state!=='normal'?':'+state:button?':not(:hover):not(:active):not(:focus-visible)':'';
 rule(selector+suffix+(button?':not(:disabled):not([aria-disabled="true"])':''),[...values.values()][0]);
}
for(const kind of ['goal-new','goal-complete','event','meet','up','down']){
 const r=manifest.records.find(r=>r.kind==='background'&&r.sources.some(s=>s.src.startsWith('assets/ui/extracted/notification-'+kind+'-')));
 if(!r)throw Error('Missing notice '+kind);
 rule('.story-notice[data-kind="'+kind+'"]',r);
}
const files={
 'src/shared/ui/generated-art.css':lines.join('\n')+'\n',
 'data/presentation/generated-art-preload.json':JSON.stringify([...new Set(used)].sort(),null,2)+'\n'
};
for(const [name,text]of Object.entries(files)){
 const dest=path.join(root,name);
 if(process.argv.includes('--write'))fs.writeFileSync(dest,text);
 else if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==text)throw Error('Generated paint stale: '+name);
}
console.log('GENERATED_UI_CSS_OK:',lines.length-1,'static state bindings;',new Set(used).size,'PNG files');
