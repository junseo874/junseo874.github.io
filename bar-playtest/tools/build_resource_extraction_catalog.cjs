const rows=[];
function walk(dir){for(const f of fs.readdirSync(path.join(root,dir),{withFileTypes:true})){const src=dir+'/'+f.name;if(f.isDirectory()){walk(src);continue;}if(!/\.png$/i.test(f.name))continue;
 // The unsliced exterior sheet is a layout example with baked-in sample dialogue.
 if(src==='assets/exterior-textbox/GRD_textbox.png')continue;
 const data=fs.readFileSync(path.join(root,src));if(data.toString('hex',0,8)!=='89504e470d0a1a0a')throw Error('Not PNG: '+src);
 const part=src.startsWith('assets/ui-parts-'),id=src.split('/').slice(2).join('/').replace(/\.png$/,'');
 const title=part?labels[id]:src.includes('exterior-textbox')?'외부 말풍선 · '+f.name:src.includes('/choices/')?'바 선택지 · '+f.name:f.name;
 if(part&&!title)throw Error('Missing part label '+src);
 rows.push({src,title,category:part?'UI · 분리 그래픽':'UI · 원본 조각',w:data.readUInt32BE(16),h:data.readUInt32BE(20),...(part?{note:id.includes('selected-background')?'텍스트 없는 가변 폭 배경 · 모서리 보존 권장':id==='tutorial/panel-background'?'본체 350×230 · 그림자용 투명 여백 포함':'현재 게임 디자인 · 투명 PNG'}:{})});
}}
for(const dir of ['assets/ui-parts-20261019','assets/ui','assets/exterior-textbox'])walk(dir);
fs.writeFileSync(path.join(root,'resource-extraction-assets.js'),'// Generated by tools/build_resource_extraction_catalog.cjs\nwindow.ResourceExtractionAssets='+JSON.stringify(rows,null,2)+';\n');
